"""Deterministic TF-IDF retrieval engine for AgriSoko Pocket.

Rules (documented for the report):
  1. One searchable document per member (name, aliases, github, role, skills,
     feature, problem, target user, contribution, metric, consented feedback).
  2. Score = 0.4 * cos + 0.6 * coverage, where
       cos      = 0.6 * cosine(word TF-IDF 1-2 grams) + 0.4 * cosine(char_wb TF-IDF 3-5 grams)
       coverage = IDF-weighted share of the question's content words found in the member
                  document (unknown words count with the highest IDF, so unrelated
                  questions score near 0). Long documents dilute plain cosine, so
                  coverage keeps short, precise questions from being under-scored.
  3. Name/alias boost: if the query contains, as a whole phrase, the member's full
     name, alias, GitHub username or a name part (>= 3 letters), +0.50 is added
     (capped at 1.0).
  4. Confidence threshold (default 0.45): below it the answer is "no match".
  4b. Ambiguity guard: without a name/alias hit, if the runner-up is within 0.05 of the
      best score the question is ambiguous and returns "no match" with suggestions.
  5. Only fields stored in members.json are returned. Nothing is generated by an LLM.
"""
from __future__ import annotations

import hashlib
import json
import re
import unicodedata
from pathlib import Path
from typing import Any

import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

MODEL_VERSION = "agrisoko-tfidf-1.0.0"
DEFAULT_THRESHOLD = 0.45
WORD_WEIGHT, CHAR_WEIGHT, NAME_BOOST = 0.6, 0.4, 0.50
COS_WEIGHT, COVER_WEIGHT, AMBIGUITY_MARGIN = 0.4, 0.6, 0.05

REQUIRED_KEYS = [
    "fullName", "registrationNumber", "aliases", "githubUsername", "role", "skills",
    "targetUser", "problem", "contribution", "feature", "outcomeMetric",
    "evidenceLinks", "testerFeedback", "introductionDraft",
]
LIST_KEYS = {"aliases", "skills", "evidenceLinks", "testerFeedback"}
STOP = set("who is the a an of in on for to me about tell what which built build made make did does do"
           " and with show give find name person member team will can you your i my be are was were".split())


def normalize(text: str) -> str:
    text = unicodedata.normalize("NFKD", str(text)).encode("ascii", "ignore").decode()
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9]+", " ", text.lower())).strip()


def slugify(text: str) -> str:
    return normalize(text).replace(" ", "-")


def file_fingerprint(path: str | Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_members(path: str | Path) -> list[dict[str, Any]]:
    """Load and validate members.json. Optional fields may be empty but never dropped."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise ValueError("members.json must contain a list of member records")
    seen: set[str] = set()
    for i, m in enumerate(data):
        missing = [k for k in REQUIRED_KEYS if k not in m]
        if missing:
            raise ValueError(f"Member #{i + 1} is missing keys: {missing}")
        for k in LIST_KEYS:
            if not isinstance(m[k], list):
                raise ValueError(f"Member #{i + 1}: '{k}' must be a list")
        if not str(m["fullName"]).strip():
            raise ValueError(f"Member #{i + 1}: fullName is empty")
        m.setdefault("id", slugify(m["fullName"]))
        if m["id"] in seen:
            raise ValueError(f"Duplicate member id: {m['id']}")
        seen.add(m["id"])
    return data


def placeholder_warnings(members: list[dict[str, Any]]) -> list[str]:
    out = []
    for m in members:
        if "REPLACE" in json.dumps(m, ensure_ascii=False):
            out.append(f"{m['fullName']}: record still contains REPLACE placeholders")
    return out


def member_document(m: dict[str, Any]) -> str:
    parts = [m["fullName"], " ".join(m["aliases"]), m["githubUsername"], m["role"],
             " ".join(m["skills"]), m["feature"], m["problem"], m["targetUser"],
             m["contribution"], m["outcomeMetric"],
             " ".join(t.get("comment", "") for t in m["testerFeedback"] if t.get("consent"))]
    return normalize(" ".join(str(p) for p in parts))


def identity_phrases(m: dict[str, Any]) -> list[str]:
    phrases = {normalize(m["fullName"]), normalize(m["githubUsername"])}
    phrases.update(normalize(a) for a in m["aliases"])
    phrases.update(p for p in normalize(m["fullName"]).split() if len(p) >= 3)
    return [p for p in phrases if p]


def make_introduction(m: dict[str, Any]) -> str:
    """Re-arranges approved facts only. No new facts, metrics or links are created."""
    def s(t: str) -> str:
        t = t.strip()
        return t if not t or t[-1] in ".!?" else t + "."
    first = m["fullName"].split()[0]
    parts = [f"My name is {first}.", s(f"I am the {m['role']}")]
    if m["feature"]:
        built = f"I built {m['feature']}"
        if m["targetUser"]:
            built += f" for {m['targetUser']}"
        parts.append(s(built))
    if m["problem"]:
        parts.append(s(f"Problem addressed: {m['problem']}"))
    if m["contribution"]:
        parts.append(s(m["contribution"]))
    if m["outcomeMetric"].strip():
        parts.append(s(f"Verified outcome: {m['outcomeMetric']}"))
    else:
        parts.append("No verified outcome metric is recorded yet; this profile states only what was built and tested.")
    n = sum(1 for t in m["testerFeedback"] if t.get("consent"))
    if n:
        parts.append(f"{n} consented tester comment(s) are recorded.")
    if m["evidenceLinks"]:
        parts.append("Repository and evidence links are listed below.")
    return " ".join(parts)


class Engine:
    def __init__(self, members: list[dict[str, Any]], threshold: float = DEFAULT_THRESHOLD):
        if not members:
            raise ValueError("Member dataset is empty")
        self.members = members
        self.threshold = threshold
        docs = [member_document(m) for m in members]
        self.word = TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True)
        self.char = TfidfVectorizer(analyzer="char_wb", ngram_range=(3, 5), sublinear_tf=True)
        self.xw = self.word.fit_transform(docs)
        self.xc = self.char.fit_transform(docs)
        self.doc_tokens = [set(d.split()) for d in docs]
        self.identities = [identity_phrases(m) for m in members]
        self.vocab = self.word.vocabulary_
        self.idf = self.word.idf_
        self.max_idf = float(self.idf.max())
        self.table = pd.DataFrame({"id": [m["id"] for m in members], "doc": docs})

    def suggestions(self) -> list[str]:
        out = []
        for m in self.members:
            out.append(f"{m['fullName']} ({m['role']})")
        return out

    def search(self, query: str) -> dict[str, Any]:
        q = normalize(query)
        if not q:
            raise ValueError("Query is empty")
        sw = cosine_similarity(self.word.transform([q]), self.xw)[0]
        sc = cosine_similarity(self.char.transform([q]), self.xc)[0]
        cos = WORD_WEIGHT * sw + CHAR_WEIGHT * sc
        content = [t for t in q.split() if t not in STOP]
        weights = [float(self.idf[self.vocab[t]]) if t in self.vocab else self.max_idf for t in content]
        total = sum(weights)
        base = []
        for i in range(len(self.members)):
            cov = (sum(w for t, w in zip(content, weights) if t in self.doc_tokens[i]) / total) if total else 0.0
            base.append(COS_WEIGHT * cos[i] + COVER_WEIGHT * cov)
        padded = f" {q} "
        scores, hits = [], []
        for i in range(len(self.members)):
            hit = next((p for p in sorted(self.identities[i], key=len, reverse=True)
                        if f" {p} " in padded), None)
            hits.append(hit)
            scores.append(min(1.0, float(base[i]) + (NAME_BOOST if hit else 0.0)))
        order = sorted(range(len(scores)), key=lambda i: scores[i], reverse=True)
        best = order[0]
        conf = round(scores[best], 4)
        terms = sorted({t for t in q.split() if t in self.doc_tokens[best] and t not in STOP})
        matched = conf >= self.threshold
        ambiguous = False
        if matched and not hits[best] and len(order) > 1 and conf - scores[order[1]] < AMBIGUITY_MARGIN:
            matched, ambiguous = False, True
        result: dict[str, Any] = {
            "query": query, "matched": matched, "confidence": conf,
            "threshold": self.threshold, "model_version": MODEL_VERSION,
            "matched_terms": terms if matched else [],
            "suggestions": [] if matched else self.suggestions(),
            "member": None, "introduction": None, "reason": "",
            "runner_up": [{"id": self.members[i]["id"], "confidence": round(scores[i], 4)} for i in order[1:3]],
        }
        if matched:
            m = self.members[best]
            result["member"] = m
            result["introduction"] = make_introduction(m)
            result["reason"] = (f"The question contains the name or alias '{hits[best]}'." if hits[best]
                                else f"Shared terms with this profile: {', '.join(terms) or 'text similarity'}.")
        elif ambiguous:
            result["reason"] = ("No confident match was found: the question fits several members equally well. "
                                "Try a name, a nickname or a more specific feature.")
        else:
            result["reason"] = (f"No confident match was found (best score {conf:.2f} is below "
                                f"the {self.threshold:.2f} threshold). Try a name, role or feature.")
        return result
